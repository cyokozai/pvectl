// newLinuxContainerFromSummary builds a list-level object from
// /cluster/resources data only (no per-container config fetch). It is
// not round-trippable: unprivileged, volumes and NICs need the config.
func newLinuxContainerFromSummary(g api.GuestSummary) *LinuxContainer {
	vmid := g.VMID
	return &LinuxContainer{
		TypeMeta: runtime.TypeMeta{APIVersion: APIVersion, Kind: KindName},
		Metadata: runtime.ObjectMeta{Name: g.Name},
		Spec: Spec{
			TargetNode: g.Node,
			VMID:       &vmid,
			Resources: Resources{
				Cores:  g.MaxCPU,
				Memory: int(g.MaxMem / (1 << 20)),
			},
			Tags: g.Tags,
		},
		Status: statusFromSummary(g),
	}
}

// newLinuxContainerFromConfig builds the full, round-trippable object
// from the container's raw config plus its cluster summary. Applying
// its yaml form yields no difference (see TestGetYAMLRoundTrip).
//
// unprivileged is always set (absent live means false, ADR-010 §3).
// osTemplate and root are never set: Proxmox records neither, and the
// root credentials are write-only (ADR-010 §4, §5).
func newLinuxContainerFromConfig(g api.GuestSummary, cfg map[string]any) *LinuxContainer {
	vmid := g.VMID
	spec := specFromConfig(g.Node, cfg)
	spec.VMID = &vmid
	name := cfgString(cfg, "hostname")
	if name == "" {
		name = g.Name
	}
	return &LinuxContainer{
		TypeMeta: runtime.TypeMeta{APIVersion: APIVersion, Kind: KindName},
		Metadata: runtime.ObjectMeta{Name: name},
		Spec:     spec,
		Status:   statusFromSummary(g),
	}
}

func statusFromSummary(g api.GuestSummary) *Status {
	return &Status{
		VMID:   g.VMID,
		Node:   g.Node,
		State:  g.Status,
		Uptime: g.Uptime,
		CPU:    g.CPU,
		MaxMem: g.MaxMem,
	}
}

// specFromConfig reverse-converts a raw Proxmox lxc config into the
// manifest spec shape.
func specFromConfig(node string, cfg map[string]any) Spec {
	unprivileged := cfgInt(cfg, keyUnpriv) == 1
	spec := Spec{
		TargetNode:   node,
		Unprivileged: &unprivileged,
		Description:  cfgString(cfg, "description"),
		Resources: Resources{
			Cores:  cfgInt(cfg, "cores"),
			Memory: cfgInt(cfg, "memory"),
		},
		Nameserver: cfgString(cfg, "nameserver"),
		Features:   featuresFromValue(cfgString(cfg, keyFeatures)),
		// Live carries onboot, not an intent: onboot=1 is Always,
		// anything else maps to Manual so export never asks apply to
		// stop a container the user did not ask to stop.
		RunStrategy: runStrategyFromOnboot(cfgInt(cfg, "onboot")),
		Tags:        splitSortTags(cfgString(cfg, "tags")),
	}
	if _, has := cfg["swap"]; has {
		swap := cfgInt(cfg, "swap")
		spec.Resources.Swap = &swap
	}
	if value := cfgString(cfg, keyRootFS); value != "" {
		v := parseVolumeValue(value)
		spec.RootFS = &RootFS{Storage: v.Storage, Size: bytesToSizeString(v.SizeBytes)}
	}

	for key, raw := range cfg {
		value, ok := raw.(string)
		if !ok {
			continue
		}
		switch {
		case rxMountKey.MatchString(key):
			if mp, ok := mountPointFromValue(key, value); ok {
				spec.MountPoints = append(spec.MountPoints, mp)
			}
		case rxNetKey.MatchString(key):
			spec.Networks = append(spec.Networks, netFromValue(key, value))
		}
	}
	sort.Slice(spec.MountPoints, func(i, j int) bool { return slotLess(spec.MountPoints[i].Name, spec.MountPoints[j].Name) })
	sort.Slice(spec.Networks, func(i, j int) bool { return slotLess(spec.Networks[i].Name, spec.Networks[j].Name) })
	return spec
}

// mountPointFromValue parses a live mpN value. Bind mounts and device
// mounts (a host path, no storage or size) cannot be expressed in
// spec.mountPoints and report ok=false; they stay reachable via raw.
func mountPointFromValue(key, value string) (MountPoint, bool) {
	v := parseVolumeValue(value)
	if v.Storage == "" || v.SizeBytes <= 0 {
		return MountPoint{}, false
	}
	return MountPoint{
		Name:    key,
		Storage: v.Storage,
		Size:    bytesToSizeString(v.SizeBytes),
		Path:    v.Opts["mp"],
	}, true
}

// netFromValue parses a live netN value. hwaddr is generated by Proxmox
// and is not exported, the same as a VM's macaddr.
func netFromValue(key, value string) Network {
	opts := parseOpts(value)
	tag, _ := strconv.Atoi(opts["tag"])
	return Network{
		Name:      key,
		Interface: opts["name"],
		Bridge:    opts["bridge"],
		IP:        opts["ip"],
		GW:        opts["gw"],
		Tag:       tag,
	}
}

// featuresFromValue maps the modelled feature flags; nil when none of
// them is present.
func featuresFromValue(value string) *Features {
	opts := parseOpts(value)
	flag := func(key string) *bool {
		v, ok := opts[key]
		if !ok {
			return nil
		}
		b := v == "1"
		return &b
	}
	f := &Features{Nesting: flag("nesting"), Keyctl: flag("keyctl"), Fuse: flag("fuse"), Mknod: flag("mknod")}
	if f.Nesting == nil && f.Keyctl == nil && f.Fuse == nil && f.Mknod == nil {
		return nil
	}
	return f
}

// slotLess orders slot names numerically, so mp10 sorts after mp2.
func slotLess(a, b string) bool {
	na, nb := slotNumber(a), slotNumber(b)
	if na != nb {
		return na < nb
	}
	return a < b
}

func slotNumber(slot string) int {
	n, err := strconv.Atoi(strings.TrimLeft(slot, "abcdefghijklmnopqrstuvwxyz"))
	if err != nil {
		return -1
	}
	return n
}

// runStrategyFromOnboot maps the live onboot flag back to a strategy.
func runStrategyFromOnboot(onboot int) RunStrategy {
	if onboot == 1 {
		return RunStrategyAlways
	}
	return RunStrategyManual
}

func splitSortTags(s string) []string {
	if s == "" {
		return nil
	}
	tags := strings.Split(s, ";")
	sort.Strings(tags)
	return tags
}

func cfgString(cfg map[string]any, key string) string {
	switch v := cfg[key].(type) {
	case string:
		return v
	case nil:
		return ""
	default:
		return fmt.Sprintf("%v", v)
	}
}

func cfgInt(cfg map[string]any, key string) int {
	switch v := cfg[key].(type) {
	case float64:
		return int(v)
	case int:
		return v
	case string:
		i, _ := strconv.Atoi(v)
		return i
	default:
		return 0
	}
}
